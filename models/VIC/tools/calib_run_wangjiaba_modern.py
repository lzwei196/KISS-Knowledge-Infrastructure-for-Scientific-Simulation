#!/usr/bin/env python3
"""Modern-era (2000-2018) sibling of calib_run_wangjiaba.py — a thin wrapper, not a fork.

The validated driver is 900 lines of inject / run / route / score / run-health machinery
that must stay identical between eras, so this imports it as a module and changes only
what the era changes:

  1. FORCING_SRC  -> the 2000-2018 build (or whatever SYS1_FORCING_ROOT points at, which
                     is how the forecast-rain variants are run).
  2. SPLITS       -> modern events. sim = 2 spin-up years + the flood year, exactly the
                     convention the 1982-1998 splits use.
  3. FORCEYEAR    -> the driver substitutes STARTYEAR/ENDYEAR into the global param but
                     NOT FORCEYEAR, which the template hard-codes to 1980. With forcing
                     that begins in 2000, VIC would silently offset every read by 20
                     years and still exit 0. This wrapper substitutes it.
  4. the 1980 floor on KDT_VIC_SPINUP_START becomes 2000, for the same reason.

Everything else — soil/veg injection, the routing chain, obs identity checks, the
fail-closed scoring — is the original code, untouched.
"""
from __future__ import annotations
import importlib.util
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _drop_stale_out() -> None:
    """codex structure_sync r2 #3: remove the --out metrics file BEFORE any check that can fail
    (the spin-up floor below runs before the base driver's own cleanup), so a failed retry can
    never leave an earlier success readable."""
    argv = sys.argv[1:]
    for i, t in enumerate(argv):
        v = argv[i + 1] if t == "--out" and i + 1 < len(argv) else (t[6:] if t.startswith("--out=") else None)
        if v:
            try:
                Path(v).unlink()
            except FileNotFoundError:
                pass
            except OSError as e:
                sys.exit(f"[calib_run] FAIL: cannot remove stale metrics file {v!r}: {e}")


if __name__ == "__main__":
    _drop_stale_out()
_spec = importlib.util.spec_from_file_location("calib_run_wangjiaba",
                                               HERE / "calib_run_wangjiaba.py")
base = importlib.util.module_from_spec(_spec)
sys.modules["calib_run_wangjiaba"] = base
_spec.loader.exec_module(base)

FORCING_START_YEAR = 2000
DEFAULT_FORCING = (f"{base.BASE}/outputs/wangjiaba_modern/vic_temp/forcing/forcing_final")

# 1. forcing source: env override first, so forecast-rain variants are one env var away
base.FORCING_SRC = os.environ.get("SYS1_FORCING_ROOT", DEFAULT_FORCING)

# 2. modern-era splits. Wangjiaba peak-over-threshold events with >= 4000 m3/s peak,
#    plus 2002 (first event of the era). sim = (peak_year-2, peak_year).
base.SPLITS = {
    "2002": {"sim": (2000, 2002), "score": ("2002-01-01", "2002-12-31")},
    "2003": {"sim": (2001, 2003), "score": ("2003-01-01", "2003-12-31")},
    "2005": {"sim": (2003, 2005), "score": ("2005-01-01", "2005-12-31")},
    "2007": {"sim": (2005, 2007), "score": ("2007-01-01", "2007-12-31")},
    "2008": {"sim": (2006, 2008), "score": ("2008-01-01", "2008-12-31")},
    "2010": {"sim": (2008, 2010), "score": ("2010-01-01", "2010-12-31")},
    "2017": {"sim": (2015, 2017), "score": ("2017-01-01", "2017-12-31")},
}

# 2b. obs envelope for the modern splits. Generated by mirroring load_obs() slicing
#     exactly (q > -90, then loc[s0:s1]) on the CNGF 王家坝 series at full float
#     precision, so the rel_tol 1e-9 asserts pass. All seven years are contiguous.
base.OBS_ENVELOPE.update({
    "2002": {"n_days": 365, "q_min": 15.3, "q_max": 5230.0, "q_sum": 109823.40000000001, "q_mean": 300.8860273972603},
    "2003": {"n_days": 365, "q_min": 41.0, "q_max": 7250.0, "q_sum": 222526.3, "q_mean": 609.6610958904109},
    "2005": {"n_days": 365, "q_min": 39.7, "q_max": 6770.0, "q_sum": 204232.0, "q_mean": 559.5397260273973},
    "2007": {"n_days": 365, "q_min": 41.0, "q_max": 7700.0, "q_sum": 185345.80000000002, "q_mean": 507.79671232876717},
    "2008": {"n_days": 366, "q_min": 41.3, "q_max": 4140.0, "q_sum": 133763.1, "q_mean": 365.4729508196721},
    "2010": {"n_days": 365, "q_min": 32.1, "q_max": 4260.0, "q_sum": 96635.5, "q_mean": 264.75479452054793},
    "2017": {"n_days": 365, "q_min": 63.8, "q_max": 4240.0, "q_sum": 158669.6, "q_mean": 434.71123287671236},
})

# 2c. forcing cache: the driver stages forcing into a FIXED /dev/shm path and checks
#     staleness by cell COUNT only. The modern build and every forecast-rain variant
#     have the same 35 cells as the 1980-1998 build, so all of them would have been
#     silently served the old cache. Key the cache on the source path instead.
import hashlib
_key = hashlib.sha1(base.FORCING_SRC.encode()).hexdigest()[:10]
base.FORCING_CACHE = f"/dev/shm/kdt_vic_calib/forcing_{base.BASIN}_{_key}"

# 3. FORCEYEAR substitution — wrap the original writer, then patch the one line
_orig_write_gp = base.write_global_param


def write_global_param(dst, soil, veg, veglib, constants, result_dir,
                       forcing_prefix, y0, y1):
    _orig_write_gp(dst, soil, veg, veglib, constants, result_dir,
                   forcing_prefix, y0, y1)
    lines = Path(dst).read_text().splitlines(keepends=True)
    out, seen = [], False
    for l in lines:
        tok = l.split()
        if tok and tok[0] == "FORCEYEAR" and not l.lstrip().startswith("#"):
            out.append(f"FORCEYEAR\t\t\t{FORCING_START_YEAR}\n")
            seen = True
        else:
            out.append(l)
    if not seen:
        raise base.Fail("global param template has no FORCEYEAR line to substitute")
    Path(dst).write_text("".join(out))


base.write_global_param = write_global_param

# 4. spin-up floor: the modern forcing starts 2000, not 1980
_orig_main = base.main


def main() -> int:
    _drop_stale_out()        # codex structure_sync r2 #3: before every fallible check
    ss = os.environ.get("KDT_VIC_SPINUP_START")
    if ss and int(ss) < FORCING_START_YEAR:
        raise base.Fail(f"KDT_VIC_SPINUP_START={ss} precedes the modern forcing "
                        f"(starts {FORCING_START_YEAR})")
    # the original guard raises below 1980; anything >= 2000 passes it untouched
    return _orig_main()


if __name__ == "__main__":
    sys.exit(main())
