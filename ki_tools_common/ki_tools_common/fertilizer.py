"""
fertilizer.py — fertiliser RATE lookup (NPKGRIDS) and application SCHEDULE for any location and crop.

Used by APEX, EPIC, DSSAT (grid ensemble) and SWAT+ tools (the four live callers found 2026-09-24).

Data source for rates: NPKGRIDS v1.08 (Nguyen, Tang, Conchedda et al. 2024, Sci Data)
  - 0.05 degree (3 arcmin), south-first latitude, ocean = -1, per crop, kg nutrient /ha /yr
  - variables per nutrient: <X>rate, <X>qual (0-1, 1 best), <X>set (which source dataset, 1-11)
  - files: NPKGRIDSv1.08_{crop}.nc ; on this host they open with the h5netcdf engine only

Two things this module never does (both were defects before 2026-09-24):
  1. drop a zero silently. A zero pixel in NPKGRIDS almost always means 'no harvested area of this crop
     in this 0.05-degree pixel' (checked against SPAM 2020: cells with crop area whose pixels are ALL
     zero hold about 1 % of harvested area for wheat, maize and rice; the rest of the zeros are the
     crop mask, e.g. the built-up core of Wuhan inside a 259 kg/ha rice region). So for a POINT lookup
     at a site the caller says grows the crop, a zero centre pixel is treated as 'no crop recorded
     here' (an INFERENCE, not a mask check) and the eight neighbouring pixels are searched
     (zero_means='no_crop_here', the default); a value found there is labelled 'npkgrids_neighbour'
     with neighbour_reason, centre_value, centre_reason and the selected pixel's coordinates. When
     every neighbour is zero as well, the zero is returned as data. Pass zero_means='zero_rate' to take
     the centre zero as the rate. Gridded campaigns should use load_rates_grid with harvested-area
     weights instead, where the mask takes care of itself.
  2. invent a number and label it as data. A number that did not come from the dataset is labelled
     'fallback' with a reason; in strict mode it is None.

Rates ------------------------------------------------------------------------------------------
    get_fertilizer_rates(lat, lon, crop, strict=False)  -> dict
      n_kgha, p_kgha, k_kgha   kg N / P / K per ha (elemental P and K, converted from P2O5 / K2O)
      source                   provenance of N; one of SOURCE_VALUES
      sources                  {'n':..., 'p':..., 'k':...} provenance per nutrient
      quality, dataset_used    the dataset's own Nqual and Nset for the cell that supplied N
      neighbour_offset_deg     (dlat, dlon) of the selected pixel from the centre pixel, else (0, 0)
      centre_value             the raw Nrate at the centre pixel as stored (-1 ocean, nan, or a number)
      centre_reason            why the centre pixel did not supply N ('ocean', 'nan', ...), else None
      neighbour_reason         why a neighbour was used: 'centre_missing' or 'centre_zero_no_crop_recorded'
      selected_lat_lon         coordinates of the pixel that supplied N; zero_policy = the zero_means used
      fallback_reason          why a fallback / missing value was returned, else None
      crop                     the dataset crop the name resolved to
    strict=False (legacy callers): missing N -> declared FALLBACK_N_RATES value, source 'fallback'.
    strict=True  (new code):       missing N -> None, source 'missing'; unknown crop raises ValueError.

Schedules --------------------------------------------------------------------------------------
    get_schedule(n_total_kgha, crop, plant_doy, maturity_doy, weather=None, events=None, ...)
      Door 1, events given: passed through untouched (copied), validated, provenance 'user'.
      Door 2, generated by a declared rule (default DEFAULT_RULE), provenance 'generated'.
    Every event: doy, year_offset, days_after_planting, n_kgha (kg N/ha, not product), material,
      depth_cm, type, trigger, rule, provenance, clipped_to, days_after_planting_unclipped, note.
    Weather arrays are indexed from DOY 1 of the PLANTING year (index 0 = 1 January) and must run to
      the end of the season, into the next year when the season wraps.

The generated rule 'ggcmi3_derived_v1' (declared; see the constants block for every number):
    20 % at sowing. 80 % on the day 25 % of the season's heat units (base TBASE_C[crop]) have
    accumulated (Jägermeyr et al. 2021, Nat Food, GGCMI phase 3 simplifying assumption). This is
    DERIVED from that protocol, not identical to it: the protocol uses a 1979-2010 reference heat
    requirement per cell; this module uses the season's own realised heat total, so it needs only the
    season's weather. Winter crops (dormant): the 80 % goes at green-up, the middle of the first full
    30-day block (counted from sowing) whose mean temperature is above 8 C and that comes after the LAST
    block at or below 8 C, i.e. after winter has ended (Franke et al. 2020 GMD phase-2 winter-wheat
    threshold; the 'after winter' condition and the sowing-anchored blocks are ours). A generic wheat /
    barley / rapeseed is the winter type when its season is 200 days or longer. Legumes: everything at
    sowing. A thermal second dose is kept between 15 % and 80 % of the season (our assumption; Franke's
    40-day / 50-day bounds normalised to a 275-day season); a green-up dose is never moved, a rail
    conflict is flagged in 'note'. No weather: the calendar-fraction fallback (25 % summer, 60 % winter),
    labelled. Season days run from planting (day 0) up to, not including, the maturity day. Nothing here
    is a measurement of farm practice.
"""

