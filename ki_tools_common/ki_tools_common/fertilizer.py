# =============================================================================== rate lookup
def _open_npkgrids(crop_file: str):
    """Open one NPKGRIDS file. The default netCDF4 engine fails on these files on this host (HDF
    error, found 2026-09-24: every lookup silently fell back); h5netcdf reads them."""
    import xarray as xr
    path = os.path.join(NPKGRIDS_DIR, f"NPKGRIDSv1.08_{crop_file}.nc")
    if not os.path.isfile(path):
        raise FileNotFoundError(path)
    last = None
    for engine in ("h5netcdf", None):
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                return xr.open_dataset(path, engine=engine) if engine else xr.open_dataset(path)
        except Exception as exc:          # noqa: BLE001 - try the next engine, report the last error
            last = exc
    raise OSError(f"cannot open {path}: {last}")


@lru_cache(maxsize=DATASET_CACHE_SIZE)
def _cached_dataset(crop_file: str):
    return _open_npkgrids(crop_file)


def _sample_dataset(ds, lat: float, lon: float) -> Dict[str, float]:
    """Raw values of every data variable at the grid cell nearest (lat, lon). No interpretation: -1 and
    NaN come back as they are. Adds '_sel_lat' / '_sel_lon', the coordinates of the pixel actually
    selected (neighbour searches offset from THESE, so float ties at pixel edges cannot skip or repeat a
    pixel). Outside the grid -> {'_error': 'outside_grid'}; a read failure -> {'_error': 'read_error:...'}."""
    try:
        cell = ds.sel(lat=lat, lon=lon, method="nearest", tolerance=NPKGRIDS_STEP_DEG / 2 + 1e-3)   # half a pixel, plus float32 coordinate slack
    except KeyError:
        return {"_error": "outside_grid"}
    try:
        out = {str(v): float(cell[v].values) for v in ds.data_vars}
        out["_sel_lat"] = float(cell["lat"].values); out["_sel_lon"] = float(cell["lon"].values)
    except Exception as exc:              # noqa: BLE001 - xarray reads lazily; the error surfaces here
        return {"_error": f"read_error:{type(exc).__name__}"}
    return out


def _sample_npkgrids_file(crop_file: str, lat: float, lon: float) -> Dict[str, float]:
    try:
        ds = _cached_dataset(crop_file)
    except Exception as exc:              # noqa: BLE001
        return {"_error": f"read_error:{type(exc).__name__}"}
    return _sample_dataset(ds, lat, lon)


def _value(raw: Optional[Dict], var: str):
    """(value or None, reason). Zero is a value. -1 is the ocean flag. NaN is missing."""
    if raw is None:
        return None, "no_dataset_for_crop"
    if "_error" in raw:
        return None, raw["_error"]
    if var not in raw:
        return None, "variable_absent"
    v = raw[var]
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return None, "nan"
    v = float(v)
    if v == NPKGRIDS_OCEAN:
        return None, "ocean"
    if not math.isfinite(v) or v < 0:
        return None, "invalid_value"
    return v, None


def _neighbour_offsets():
    s = NPKGRIDS_STEP_DEG
    return [(dlat, dlon) for dlat in (-s, 0.0, s) for dlon in (-s, 0.0, s) if not (dlat == 0.0 and dlon == 0.0)]


def get_fertilizer_rates(lat: float, lon: float, crop: str = "maize", strict: bool = False,
                         sampler=None, allow_neighbour: bool = True, zero_means: str = "no_crop_here") -> Dict:
    """Look up N/P/K application rates for a crop at a location. See the module docstring.

    sampler(crop_file, lat, lon) -> raw dataset dict; injectable for tests. Default reads NPKGRIDS.
    zero_means: 'no_crop_here' (default; a zero centre pixel triggers the neighbour search) or
                'zero_rate' (a zero centre pixel is the rate).
    """
    if zero_means not in ("no_crop_here", "zero_rate"):
        raise ValueError("zero_means must be 'no_crop_here' or 'zero_rate'")
    crop_in = str(crop).lower().strip()
    crop_file = NPKGRIDS_CROPS.get(crop_in)
    known = crop_file is not None or crop_in in FALLBACK_N_RATES
    if strict and not known:
        raise ValueError(f"unknown crop {crop!r}; known: {sorted(set(NPKGRIDS_CROPS) | set(FALLBACK_N_RATES))}")
    sampler = sampler or _sample_npkgrids_file

    centre = sampler(crop_file, lat, lon) if crop_file else None
    n, n_reason = _value(centre, "Nrate")
    centre_reason = n_reason                              # the original reason survives a neighbour hit
    centre_raw_n = None if centre is None or "_error" in centre else centre.get("Nrate")
    raw_n = centre                                        # the record that supplies N (and its Nqual / Nset)
    src_n = "npkgrids" if n is not None else None
    offset, neighbour_reason = (0.0, 0.0), None
    sel = (centre.get("_sel_lat", lat), centre.get("_sel_lon", lon)) if isinstance(centre, dict) else (lat, lon)
    centre_zero = n is not None and n == 0.0 and zero_means == "no_crop_here"
    searchable = crop_file and n_reason not in ("no_dataset_for_crop",) and not str(n_reason).startswith("read_error")
    if allow_neighbour and searchable and (n is None or centre_zero):
        # offsets from the SELECTED centre pixel, so a query on a pixel edge cannot skip or repeat a neighbour;
        # pass 1 takes the first positive neighbour, pass 2 (missing centre only) accepts a zero neighbour
        cands = [(dlat, dlon, sampler(crop_file, sel[0] + dlat, sel[1] + dlon)) for dlat, dlon in _neighbour_offsets()]
        for accept_zero in ((False, True) if not centre_zero else (False,)):
            for dlat, dlon, cand in cands:
                n_c, _ = _value(cand, "Nrate")
                if n_c is not None and (n_c > 0.0 or accept_zero):
                    raw_n, n, src_n = cand, n_c, "npkgrids_neighbour"
                    offset = (round(cand.get("_sel_lat", sel[0] + dlat) - sel[0], 6), round(cand.get("_sel_lon", sel[1] + dlon) - sel[1], 6)) \
                        if isinstance(cand, dict) else (dlat, dlon)
                    neighbour_reason = "centre_zero_no_crop_recorded" if centre_zero else "centre_missing"
                    n_reason = None
                    break
            if n_reason is None:
                break

    result: Dict = {"crop": crop_file or crop_in, "neighbour_offset_deg": offset, "neighbour_reason": neighbour_reason,
                    "centre_value": centre_raw_n, "centre_reason": centre_reason, "zero_policy": zero_means,
                    "selected_lat_lon": (raw_n.get("_sel_lat", sel[0] + offset[0]), raw_n.get("_sel_lon", sel[1] + offset[1]))
                    if isinstance(raw_n, dict) and "_error" not in raw_n else None,
                    "fallback_reason": None, "quality": None, "dataset_used": None}
    sources = {}
    if n is not None:
        result["n_kgha"] = round(n, 1)
        sources["n"] = src_n
        q, _ = _value(raw_n, "Nqual")
        d, _ = _value(raw_n, "Nset")
        result["quality"] = q
        result["dataset_used"] = int(d) if d is not None else None
    elif strict:
        result["n_kgha"] = None
        sources["n"] = "missing"
        result["fallback_reason"] = n_reason
    else:
        if crop_in in FALLBACK_N_RATES:
            result["n_kgha"] = float(FALLBACK_N_RATES[crop_in])
            result["fallback_reason"] = f"{n_reason}:declared_crop_table"
        elif crop_file and crop_file in FALLBACK_N_RATES:
            result["n_kgha"] = float(FALLBACK_N_RATES[crop_file])
            result["fallback_reason"] = f"{n_reason}:declared_crop_table"
        else:
            result["n_kgha"] = float(FALLBACK_N_UNKNOWN_CROP)
            result["fallback_reason"] = f"{n_reason}:unknown_crop_generic_default"
        sources["n"] = "fallback"

    for key, var, factor, ratio in (("p_kgha", "P2O5rate", P2O5_TO_P, FALLBACK_P_TO_N),
                                    ("k_kgha", "K2Orate", K2O_TO_K, FALLBACK_K_TO_N)):
        nut = key[0]
        v, _ = _value(centre, var)                         # an observed centre nutrient is never discarded
        v_src = "npkgrids"
        if v is None and raw_n is not centre:
            v, _ = _value(raw_n, var)
            v_src = "npkgrids_neighbour"
        if v is not None:
            result[key] = round(v * factor, 1)
            sources[nut] = v_src
        elif strict:
            result[key] = None
            sources[nut] = "missing"
        else:
            base = result["n_kgha"] if isinstance(result["n_kgha"], (int, float)) else 0.0
            result[key] = round(float(base) * ratio, 1)
            sources[nut] = "fallback"

    result["sources"] = sources
    result["source"] = sources["n"]
    if result["source"] not in SOURCE_VALUES:
        raise RuntimeError(f"internal: source {result['source']!r} not in SOURCE_VALUES")
    return result


