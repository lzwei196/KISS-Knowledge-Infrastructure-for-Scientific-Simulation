def _crop_class(crop_lower: str, season_len: int) -> str:
    """legume / winter / summer. An explicit winter name is winter; a generic wheat/barley/rapeseed is winter
    when its sowing-to-maturity span is WINTER_SEASON_MIN_DAYS or longer (a southern winter need not cross
    January, so 'wraps the year' is not the test)."""
    if crop_lower in LEGUMES:
        return "legume"
    if crop_lower in WINTER_CROPS or (crop_lower in MAY_BE_WINTER and season_len >= WINTER_SEASON_MIN_DAYS):
        return "winter"
    return "summer"


def _tmean_series(weather: Dict, plant_doy: int, season_len: int) -> np.ndarray:
    if "tmean_c" in weather:
        t = np.asarray(weather["tmean_c"], dtype=float)
    else:
        try:
            tx = np.asarray(weather["temp_max_c"], dtype=float); tn = np.asarray(weather["temp_min_c"], dtype=float)
        except KeyError as exc:
            raise ValueError("weather needs 'tmean_c' or both 'temp_max_c' and 'temp_min_c'") from exc
        if tx.shape != tn.shape or tx.ndim != 1:
            raise ValueError(f"temp_max_c and temp_min_c must be 1-D arrays of the same length, got {tx.shape} and {tn.shape}")
        t = (tx + tn) / 2.0
    start = plant_doy - 1
    if t.ndim != 1 or t.size < start + season_len:
        raise ValueError(f"weather covers {t.size} days; the season needs index {start + season_len - 1} "
                         "(arrays start at DOY 1 of the planting year)")
    s = t[start:start + season_len]
    if not np.all(np.isfinite(s)):
        raise ValueError("weather has non-finite temperatures inside the season")
    return s


def _thermal_day(tmean: np.ndarray, tbase: float) -> Optional[int]:
    hu = np.maximum(0.0, tmean - tbase)
    total = float(hu.sum())
    if total <= 0.0:
        return None
    cum = np.cumsum(hu)
    return int(np.argmax(cum >= THERMAL_FRACTION * total))


def _green_up_day(tmean: np.ndarray):
    """(day, note). Full 30-day blocks counted from sowing (a trailing partial block is ignored). Green-up =
    the middle (start + 15) of the first block with mean > 8 C that comes AFTER THE LAST block with mean
    <= 8 C, i.e. after winter has ended, so an autumn warm spell before the main winter cannot fire it.
    note 'no_dormancy_detected' when no block is at or below 8 C; 'no_green_up_found' when the season
    has no full warm block after its last cold block."""
    n = tmean.size
    means = [(k, float(tmean[k:k + GREEN_UP_BLOCK_DAYS].mean()))
             for k in range(0, n - GREEN_UP_BLOCK_DAYS + 1, GREEN_UP_BLOCK_DAYS)]
    cold = [i for i, (_, m) in enumerate(means) if m <= GREEN_UP_THRESHOLD_C]
    if not cold:
        return None, "no_dormancy_detected"
    last_cold = cold[-1]
    for k, m in means[last_cold + 1:]:
        if m > GREEN_UP_THRESHOLD_C:
            return k + GREEN_UP_BLOCK_DAYS // 2, None
    return None, "no_green_up_found"


def _event(plant_doy, dap, n_kgha, year_len, *, etype, trigger, rule, provenance, material, depth_cm,
           clipped_to=None, dap_unclipped=None, note=None):
    absolute = plant_doy - 1 + int(dap)
    return {
        "doy": absolute % year_len + 1,
        "year_offset": absolute // year_len,
        "days_after_planting": int(dap),
        "n_kgha": float(n_kgha),
        "material": material,
        "depth_cm": depth_cm,
        "type": etype,
        "trigger": trigger,
        "rule": rule,
        "provenance": provenance,
        "clipped_to": clipped_to,
        "days_after_planting_unclipped": int(dap_unclipped) if dap_unclipped is not None else int(dap),
        "note": note,
    }


def _user_events(n_total: float, events: Sequence[Dict], plant_doy: int, year_len: int,
                 material: str, depth_cm: float) -> List[Dict]:
    out = []
    total = 0.0
    for i, ev in enumerate(events):
        if not isinstance(ev, dict) or "doy" not in ev or "n_kgha" not in ev:
            raise ValueError(f"event {i}: needs 'doy' and 'n_kgha'")
        e = copy.deepcopy(ev)
        amt = float(e["n_kgha"])
        if not math.isfinite(amt) or amt < 0:
            raise ValueError(f"event {i}: n_kgha must be finite and >= 0, got {e['n_kgha']!r}")
        if float(e["doy"]) != int(e["doy"]) or float(e.get("year_offset", 0)) != int(e.get("year_offset", 0)):
            raise ValueError(f"event {i}: doy and year_offset must be whole numbers, got {e['doy']!r} / {e.get('year_offset', 0)!r}")
        doy = int(e["doy"])
        if not 1 <= doy <= year_len:
            raise ValueError(f"event {i}: doy {doy} outside 1..{year_len}; use year_offset for the next year")
        yoff = int(e.get("year_offset", 0))
        dep = float(e.get("depth_cm", depth_cm))
        if not math.isfinite(dep) or dep < 0:
            raise ValueError(f"event {i}: depth_cm must be finite and >= 0")
        dap = (doy - 1 + yoff * year_len) - (plant_doy - 1)
        total += amt
        e.update({
            "doy": doy, "year_offset": yoff, "days_after_planting": int(dap), "n_kgha": amt,
            "material": e.get("material", material), "depth_cm": dep,
            "type": e.get("type", "user"), "trigger": "user", "rule": "user_events", "provenance": "user",
            "clipped_to": None, "days_after_planting_unclipped": int(dap), "note": e.get("note"),
        })
        out.append(e)
    if abs(total - n_total) > SUM_TOLERANCE_KGHA:
        raise ValueError(f"user events sum to {total:.3f} kg N/ha but n_total_kgha is {n_total:.3f} "
                         f"(tolerance {SUM_TOLERANCE_KGHA}); refused, not rescaled")
    return out


def get_schedule(n_total_kgha: float, crop: str, plant_doy: int, maturity_doy: int, weather: Optional[Dict] = None,
                 events: Optional[Sequence[Dict]] = None, year_len: int = 365, rule: Optional[str] = None,
                 tbase_c: Optional[float] = None, material: str = DEFAULT_MATERIAL,
                 depth_cm: float = DEFAULT_DEPTH_CM) -> List[Dict]:
    """Fertiliser N application events for one season. See the module docstring for the rule.

    n_total_kgha : total N for the season, kg N/ha (nutrient, not product)
    plant_doy, maturity_doy : day of year; the season wraps the year when maturity < planting. Season days are
        counted from planting (day 0) up to but not including the maturity day.
    weather : {'temp_max_c', 'temp_min_c'} or {'tmean_c'} daily arrays from DOY 1 of the planting year
    events : the user's own schedule (door 1); [] means 'no application' and needs n_total 0
    rule : None -> DEFAULT_RULE (legumes -> 'legume_all_at_sowing'); or one of RULES
    """
    n_total = float(n_total_kgha)
    if not math.isfinite(n_total) or n_total < 0:
        raise ValueError(f"n_total_kgha must be finite and >= 0, got {n_total_kgha!r}")
    plant_doy, maturity_doy = int(plant_doy), int(maturity_doy)
    if not (1 <= plant_doy <= year_len and 1 <= maturity_doy <= year_len):
        raise ValueError("plant_doy and maturity_doy must be within 1..year_len")
    season_len = (maturity_doy - plant_doy) % year_len
    if season_len == 0:
        raise ValueError("maturity_doy equals plant_doy: zero-length season")
    if events is not None:
        if len(events) == 0:
            if n_total > SUM_TOLERANCE_KGHA:
                raise ValueError("events=[] means no application, but n_total_kgha > 0")
            return []
        return _user_events(n_total, events, plant_doy, year_len, material, depth_cm)

    if n_total == 0.0:
        return []

    crop_lower = str(crop).lower().strip()
    cls = _crop_class(crop_lower, season_len)
    if rule is None:
        rule = "legume_all_at_sowing" if cls == "legume" else DEFAULT_RULE
    if rule not in RULES or rule == "user_events":
        raise ValueError(f"unknown rule {rule!r}; choose from {RULES}")
    if tbase_c is not None and not math.isfinite(float(tbase_c)):
        raise ValueError("tbase_c must be finite")
    if not math.isfinite(float(depth_cm)) or float(depth_cm) < 0:
        raise ValueError("depth_cm must be finite and >= 0")
    kw = dict(rule=rule, provenance="generated", material=material, depth_cm=depth_cm)

    if rule in ("legume_all_at_sowing", "all_at_sowing") or season_len < MIN_SEASON_DAYS:
        note = None if season_len >= MIN_SEASON_DAYS else "season_too_short_all_at_sowing"
        return [_event(plant_doy, 0, n_total, year_len, etype="at_planting", trigger="sowing", note=note, **kw)]

    if rule == "rice_three_dose":
        out, given = [], 0.0
        for i, (share, frac, etype) in enumerate(RICE_THREE_DOSE):
            amt = n_total - given if i == len(RICE_THREE_DOSE) - 1 else n_total * share
            given += amt
            out.append(_event(plant_doy, round(frac * season_len), amt, year_len, etype=etype,
                              trigger="sowing" if frac == 0 else "calendar_fraction", **kw))
        return out

    # ---- ggcmi3_derived_v1
    first = n_total * SOWING_SHARE
    second = n_total - first
    lo, hi = round(LOWER_RAIL_FRAC * season_len), round(UPPER_RAIL_FRAC * season_len)
    note, trigger, dap = None, None, None
    if weather is not None:
        tmean = _tmean_series(weather, plant_doy, season_len)
        if cls == "winter":
            dap, note = _green_up_day(tmean)
            trigger = "green_up"
            if dap is None and note == "no_dormancy_detected":
                tb = TBASE_C.get(crop_lower, TBASE_DEFAULT_C) if tbase_c is None else float(tbase_c)
                dap, trigger = _thermal_day(tmean, tb), "thermal_time"
        else:
            tb = TBASE_C.get(crop_lower, TBASE_DEFAULT_C) if tbase_c is None else float(tbase_c)
            dap, trigger = _thermal_day(tmean, tb), "thermal_time"
            if dap is None:
                note = "zero_heat_accumulation"
    if dap is None:
        frac = WINTER_FALLBACK_FRACTION if cls == "winter" else SUMMER_FALLBACK_FRACTION
        dap, trigger = round(frac * season_len), "calendar_fraction_fallback"
        if weather is None:
            note = note or "no_weather"

    dap_raw, clipped = dap, None
    if trigger == "green_up":                             # a detected green-up is never moved: moving it earlier
        if dap > hi:                                      # puts the dose back into dormancy; moving it later has
            note = "green_up_after_upper_rail_not_clipped"   # no basis. The conflict is flagged instead.
        elif dap < lo:
            note = "green_up_before_lower_rail_not_clipped"
    elif dap > hi:
        dap, clipped = hi, "upper"
    elif dap < lo:
        dap, clipped = lo, "lower"
    return [
        _event(plant_doy, 0, first, year_len, etype="at_planting", trigger="sowing", **kw),
        _event(plant_doy, dap, second, year_len, etype="topdress", trigger=trigger, clipped_to=clipped,
               dap_unclipped=dap_raw, note=note, **kw),
    ]


def get_split_schedule(n_total_kgha: float, crop: str = "maize", plant_doy: int = 150,
                       maturity_doy: Optional[int] = None) -> list:
    """LEGACY fixed-offset schedule kept for EPIC and SWAT+ (keys type, doy, n_kgha unchanged).
    Every event carries rule='legacy_fixed_offsets' so nobody mistakes it for the dynamic rule.
    Changed 2026-09-24: wheat top-dressings were absolute DOY 75 and 120 (wrong hemisphere, ignored the
    planting date); now LEGACY_WHEAT_SPLIT offsets from planting, wrapped into 1..365. 'winter_wheat' and
    'spring_wheat' are explicit; generic 'wheat' with maturity_doy is classed by season length
    (WINTER_SEASON_MIN_DAYS); generic 'wheat' without maturity_doy is ASSUMED winter and every event says so
    in 'note' (SWAT+ and EPIC pass generic 'wheat' without maturity: they should pass it).
    Changed 2026-10-15 (codex kiss_sync review): when maturity_doy is given, EVERY dose must fall before
    maturity (days_after_planting < season length, season = (maturity_doy - plant_doy) mod 365). A fixed
    table that does not fit the season (e.g. explicit 'winter_wheat' with a 168-day GGCMI season: the
    +195 d dose would land after harvest) RAISES ValueError; doses are never shifted or dropped to fit.
    maturity_doy == plant_doy (a zero-day season) also raises. Without maturity_doy nothing can be checked."""
    crop_lower = str(crop).lower()
    n = float(n_total_kgha)
    plant_doy = int(plant_doy)
    season = None
    if maturity_doy is not None:
        season = (int(maturity_doy) - plant_doy) % LEGACY_YEAR_LEN
        if season == 0:
            raise ValueError(f"get_split_schedule: maturity_doy {maturity_doy} equals plant_doy {plant_doy}; "
                             f"a zero-day season cannot hold any fertilizer dose")

    def ev(offset, amt, etype, note=None):
        return {"doy": (plant_doy - 1 + offset) % LEGACY_YEAR_LEN + 1, "n_kgha": amt, "type": etype,
                "days_after_planting": offset, "trigger": "fixed_offset", "rule": "legacy_fixed_offsets",
                "provenance": "generated", "note": note}

    def split(table, note=None):
        if season is not None:
            late = [(off, etype) for off, _share, etype in table if off >= season]
            if late:
                raise ValueError(
                    f"get_split_schedule: crop {crop!r} fixed-offset schedule does not fit the season "
                    f"(plant_doy {plant_doy}, maturity_doy {maturity_doy}, {season} days): dose(s) "
                    + ", ".join(f"{etype} at +{off} d" for off, etype in late)
                    + " would fall on or after maturity. Pass a crop class whose schedule fits this season, "
                      "or use get_schedule() (dynamic rule); no dose is shifted to fit.")
        return [ev(off, round(n * share, RATE_DECIMALS), etype, note) for off, share, etype in table]

    if crop_lower in LEGUMES:
        return [ev(0, n, "at_planting")]
    if crop_lower == "winter_wheat":
        return split(LEGACY_WHEAT_SPLIT)
    if crop_lower == "spring_wheat":
        return split(LEGACY_DEFAULT_SPLIT)
    if crop_lower == "wheat":
        if maturity_doy is None:                          # the caller did not say: winter type ASSUMED, and said so
            return split(LEGACY_WHEAT_SPLIT, note="class_assumed_winter_wheat_pass_maturity_doy_or_use_winter_wheat_or_spring_wheat")
        return split(LEGACY_WHEAT_SPLIT if season >= WINTER_SEASON_MIN_DAYS else LEGACY_DEFAULT_SPLIT)
    if crop_lower in ("rice", "paddy_rice"):
        return split(LEGACY_RICE_SPLIT)
    return split(LEGACY_DEFAULT_SPLIT)


def schedule_from_site(lat: float, lon: float, year: int, crop: str, n_total_kgha: float,
                       forcing_source: str = "mswx", irrigation: str = "rf", **kw) -> Dict:
    """Convenience: crop calendar + daily forcing for the site, then get_schedule(). Returns
    {'events': [...], 'plant_doy', 'maturity_doy', 'calendar_source', 'weather_source'}."""
    import calendar as _cal
    from . import crop_calendar
    if "weather" in kw:
        raise ValueError("schedule_from_site loads the weather itself; call get_schedule directly to pass your own")
    cal = crop_calendar.get_planting_harvest(lat, lon, crop=crop, irrigation=irrigation)
    plant, mat = int(cal["plant_doy"]), int(cal["harvest_doy"])
    year_len = 366 if _cal.isleap(int(year)) else 365     # the planting year's own length (cross-year DOYs are
    kw.setdefault("year_len", year_len)                   # counted with this one length: a declared simplification)
    if kw.get("events") is not None:                      # the user's own schedule needs no weather
        events = get_schedule(n_total_kgha, crop, plant, mat, weather=None, **kw)
        return {"events": events, "plant_doy": plant, "maturity_doy": mat, "calendar_source": cal.get("source"), "weather_source": None}
    from . import load_forcing
    wraps = mat < plant
    w = load_forcing.load_daily_forcing(forcing_source, lat, lon, year, year + 1 if wraps else year)
    events = get_schedule(n_total_kgha, crop, plant, mat, weather=w, **kw)
    return {"events": events, "plant_doy": plant, "maturity_doy": mat,
            "calendar_source": cal.get("source"), "weather_source": forcing_source}


# =============================================================================== whole-grid reader
def aggregate_rates_block(rates: np.ndarray, quality: np.ndarray, block: int = 2, weights: Optional[np.ndarray] = None,
                          dataset_codes: Optional[np.ndarray] = None, missing=(NPKGRIDS_OCEAN,)) -> Dict[str, np.ndarray]:
    """Aggregate block x block pixels to one cell. Zero is data; NaN, the ocean flag and negatives are
    excluded. n_kgha = weighted mean (weights = harvested crop area when given; equal otherwise), quality
    = minimum over the CONTRIBUTING pixels (valid and weight > 0; conservative), n_pixels = valid count,
    n_contributing = contributing count, and when dataset_codes is given, dataset_used = the most common
    code among contributing pixels and dataset_mixed = more than one such code in the cell."""
    r = np.asarray(rates, dtype=float)
    q = np.asarray(quality, dtype=float)
    if r.shape != q.shape or r.ndim != 2:
        raise ValueError("rates and quality must be 2-D arrays of the same shape")
    H, W = r.shape
    if H % block or W % block:
        raise ValueError(f"shape {r.shape} is not divisible by block {block}; partial blocks are not aggregated")
    valid = np.isfinite(r) & (r >= 0)
    for m in missing:
        valid &= r != m
    w = np.ones_like(r) if weights is None else np.asarray(weights, dtype=float)
    if w.shape != r.shape:
        raise ValueError("weights must match the rates shape")
    w = np.where(valid & np.isfinite(w) & (w >= 0), w, 0.0)

    def blk(a):
        return a.reshape(H // block, block, W // block, block)

    wsum = blk(w).sum(axis=(1, 3))
    num = blk(np.where(valid, r, 0.0) * w).sum(axis=(1, 3))
    with np.errstate(invalid="ignore", divide="ignore"):
        mean = np.where(wsum > 0, num / wsum, np.nan)
    contrib = valid & (w > 0)                              # metadata describes the pixels that shaped the mean
    n_pixels = blk(valid.astype(int)).sum(axis=(1, 3))
    n_contrib = blk(contrib.astype(int)).sum(axis=(1, 3))
    qmin = blk(np.where(contrib & np.isfinite(q) & (q >= 0), q, np.inf)).min(axis=(1, 3))
    qmin = np.where(np.isfinite(qmin), qmin, np.nan)
    out = {"n_kgha": mean, "quality": qmin, "n_pixels": n_pixels, "n_contributing": n_contrib, "weight_sum": wsum}
    if dataset_codes is not None:
        c = np.asarray(dataset_codes, dtype=float)
        if c.shape != r.shape:
            raise ValueError("dataset_codes must match the rates shape")
        codes = np.unique(c[contrib & np.isfinite(c) & (c >= 0)]).astype(int)
        counts = np.stack([blk((contrib & (c == k)).astype(int)).sum(axis=(1, 3)) for k in codes]) if codes.size \
            else np.zeros((1, H // block, W // block), int)
        present = counts > 0
        mode = codes[counts.argmax(axis=0)] if codes.size else np.full((H // block, W // block), -1)
        out["dataset_used"] = np.where(present.any(axis=0), mode, -1)
        out["dataset_mixed"] = present.sum(axis=0) > 1
    return out


def load_rates_grid(crop: str, target_resolution_deg: float = 0.1, nutrient: str = "N",
                    weights: Optional[np.ndarray] = None) -> Dict[str, np.ndarray]:
    """Read one NPKGRIDS crop file once and aggregate it to a coarser grid with aggregate_rates_block.
    Returns lat, lon (cell centres, south-first as the file), n_kgha, quality, n_pixels, dataset_used,
    dataset_mixed, coverage (valid pixels / block^2). Units: kg nutrient/ha (P2O5 and K2O converted)."""
    crop_file = NPKGRIDS_CROPS.get(str(crop).lower())
    if crop_file is None:
        raise ValueError(f"no NPKGRIDS file for crop {crop!r}")
    ratio = target_resolution_deg / NPKGRIDS_STEP_DEG
    block = int(round(ratio))
    if block < 1 or abs(ratio - block) > 1e-6:
        raise ValueError(f"target resolution {target_resolution_deg} is not a multiple of {NPKGRIDS_STEP_DEG}")
    var = {"N": "N", "P": "P2O5", "K": "K2O"}[nutrient.upper()]
    factor = {"N": 1.0, "P": P2O5_TO_P, "K": K2O_TO_K}[nutrient.upper()]
    ds = _cached_dataset(crop_file)
    rates = ds[f"{var}rate"].values.astype(float)
    qual = ds[f"{var}qual"].values.astype(float)
    dset = ds[f"{var}set"].values.astype(float)
    lat = np.asarray(ds["lat"].values, dtype=float)
    lon = np.asarray(ds["lon"].values, dtype=float)
    if ds[f"{var}rate"].dims != ("lat", "lon"):
        rates, qual, dset = (np.transpose(a) for a in (rates, qual, dset))
    out = aggregate_rates_block(rates, qual, block=block, weights=weights, dataset_codes=dset)
    out["n_kgha"] = out["n_kgha"] * factor
    out["lat"] = lat.reshape(-1, block).mean(axis=1)
    out["lon"] = lon.reshape(-1, block).mean(axis=1)
    out["coverage"] = out["n_pixels"] / float(block * block)
    out["nutrient"] = nutrient.upper()
    out["crop"] = crop_file
    return out
